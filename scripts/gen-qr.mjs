// Writes src/content/qr.js: the QR matrix for the deck's own address (src/content/site.js).
// Run it after changing SITE_URL; "npm test" fails while the two disagree.
//   npm run gen:qr
import { writeFileSync } from "node:fs";
import QRCode from "qrcode";
import { SITE_URL } from "../src/content/site.js";

const qr = QRCode.create(SITE_URL, { errorCorrectionLevel: "M" });
const n = qr.modules.size;
const rows = [];
for (let y = 0; y < n; y++) {
  let row = "";
  for (let x = 0; x < n; x++) row += qr.modules.get(x, y) ? "1" : "0";
  rows.push(row);
}
const out = `// Generated by scripts/gen-qr.mjs from SITE_URL in site.js. Do not edit by hand: npm run gen:qr
export const QR_TEXT = ${JSON.stringify(SITE_URL)};
export const QR_ROWS = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL("../src/content/qr.js", import.meta.url), out);
console.log(`QR ${n}x${n} for ${SITE_URL} written to src/content/qr.js`);
