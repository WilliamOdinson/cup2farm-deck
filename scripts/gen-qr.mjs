// Dev-time helper: writes src/content/qr.js with a real, scannable QR matrix.
//   node scripts/gen-qr.mjs
import { writeFileSync } from "node:fs";
import QRCode from "qrcode";

const TEXT = "CUP2FARM DEMO. LOT UG-GLC-0417. SAMPLE DATA.";
const qr = QRCode.create(TEXT, { errorCorrectionLevel: "M" });
const n = qr.modules.size;
const rows = [];
for (let y = 0; y < n; y++) {
  let row = "";
  for (let x = 0; x < n; x++) row += qr.modules.get(x, y) ? "1" : "0";
  rows.push(row);
}
const out = `// Generated by scripts/gen-qr.mjs. Encodes: ${JSON.stringify(TEXT)}
export const QR_TEXT = ${JSON.stringify(TEXT)};
export const QR_ROWS = ${JSON.stringify(rows, null, 2)};
`;
writeFileSync(new URL("../src/content/qr.js", import.meta.url), out);
console.log(`QR ${n}x${n} written`);
